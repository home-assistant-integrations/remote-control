#!/usr/bin/env python3
"""Generates the firmware's icons, fonts and time-zone table.

Run with `make assets`. The output in components/assets/generated/ is
committed, so a normal build does not need this script or Pillow.

Sources are downloaded once at pinned versions, checked against SHA-256, and
cached in toolchain/assets-cache/:

- Material Design Icons webfont (@mdi/font, Apache-2.0)
- Noto Sans (@expo-google-fonts/noto-sans, SIL Open Font License 1.1)
- posix_tz_db zones.json (nayarsystems/posix_tz_db, MIT)

Outputs:

- icons.bin     4-bit grayscale icons, 32 and 48 px, two pixels per byte,
                high nibble = left pixel, 15 = full ink
- icons_gen.c   sorted name table with offsets into icons.bin
- *.vlw         smooth fonts in the VLW format that M5GFX loads
- tz_table_gen.c  sorted IANA name -> POSIX TZ rule table
- preview.png   contact sheet of all icons and font samples (not committed)
"""

import argparse
import hashlib
import io
import json
import re
import struct
import sys
import tarfile
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SOURCES = {
    "mdi": (
        "https://registry.npmjs.org/@mdi/font/-/font-7.4.47.tgz",
        "66131558352dc8df724feac30f3b7bf7ee7311a79e4f8436f3637c0993edb773",
    ),
    "noto": (
        "https://registry.npmjs.org/@expo-google-fonts/noto-sans/-/noto-sans-0.4.2.tgz",
        "98cf14a19b8e67a0e76bfd4d5df98937b9734e6dde570bd750f2259042042548",
    ),
    "tz": (
        "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/"
        "fb5fa340cfa7599467358a347e5d6e6724d92bb2/zones.json",
        "b95662f059d0bf1408962272cb98da4820fa0e20c7582e0aca1d0613e33986ef",
    ),
}

ICON_SIZES = (32, 48)

# name, Noto Sans style, pixel size
FONTS = (
    ("font_20", "400Regular/NotoSans_400Regular.ttf", 20),
    ("font_28", "600SemiBold/NotoSans_600SemiBold.ttf", 28),
    ("font_36", "700Bold/NotoSans_700Bold.ttf", 36),
)

# Latin-1, Latin Extended-A, and ‹ › … (· is in Latin-1)
FONT_CHARS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x100, 0x180))
    + [0x2026, 0x2039, 0x203A]
)


def fetch(cache: Path, key: str) -> bytes:
    url, sha = SOURCES[key]
    path = cache / Path(url).name
    if not path.exists():
        print(f"downloading {url}")
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        path.write_bytes(data)
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha:
        path.unlink()
        sys.exit(f"checksum mismatch for {url}: {digest}")
    return data


def tar_member(data: bytes, name: str) -> bytes:
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as t:
        f = t.extractfile("package/" + name)
        if f is None:
            sys.exit(f"{name} not found in archive")
        return f.read()


# ---- icons ----


def mdi_codepoints(scss: str) -> dict:
    return {m[1]: int(m[2], 16) for m in re.finditer(r'"([a-z0-9-]+)": (F[0-9A-F]{4})', scss)}


def read_icon_list(path: Path) -> list:
    names = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line.removeprefix("mdi:"))
    return sorted(set(names))


def render_icon(ttf: bytes, codepoint: int, size: int) -> Image.Image:
    font = ImageFont.truetype(io.BytesIO(ttf), size)
    img = Image.new("L", (size, size), 0)
    ImageDraw.Draw(img).text((size / 2, size / 2), chr(codepoint), font=font, fill=255,
                             anchor="mm")
    return img


def pack4(img: Image.Image) -> bytes:
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        for x in range(0, w, 2):
            hi = (px[x, y] + 8) * 15 // 255
            lo = (px[x + 1, y] + 8) * 15 // 255 if x + 1 < w else 0
            out.append((min(hi, 15) << 4) | min(lo, 15))
    return bytes(out)


def write_icons(out: Path, names: list, cps: dict, ttf: bytes) -> list:
    missing = [n for n in names if n not in cps]
    if missing:
        sys.exit("unknown MDI icons in assets/icons.txt: " + ", ".join(missing))
    blob = bytearray()
    rows = []
    previews = []
    for name in names:
        offsets = []
        for size in ICON_SIZES:
            img = render_icon(ttf, cps[name], size)
            offsets.append(len(blob))
            blob += pack4(img)
            if size == 48:
                previews.append((name, img))
        rows.append((name, offsets))
    (out / "icons.bin").write_bytes(bytes(blob))

    lines = [
        "/* Generated by tools/gen_assets.py from assets/icons.txt. Do not edit. */",
        "",
        '#include "assets.h"',
        "",
        "const icon_entry_t icon_table[] = {",
    ]
    for name, (o32, o48) in rows:
        lines.append(f'    {{"{name}", {o32}, {o48}}},')
    lines += [
        "};",
        "",
        f"const int icon_count = {len(rows)};",
        f"const unsigned icon_blob_size = {len(blob)};",
        "",
    ]
    (out / "icons_gen.c").write_text("\n".join(lines))
    print(f"icons: {len(rows)} icons, {len(blob)} bytes")
    return previews


# ---- fonts ----


def write_vlw(path: Path, ttf: bytes, size: int):
    font = ImageFont.truetype(io.BytesIO(ttf), size)
    ascent, descent = font.getmetrics()
    metrics = bytearray()
    bitmaps = bytearray()
    count = 0
    for cp in FONT_CHARS:
        ch = chr(cp)
        advance = round(font.getlength(ch))
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        if cp == 0x20 or w == 0 or h == 0:
            w = h = 0
            ox = oy = 0
            data = b""
        else:
            img = Image.frombytes("L", (w, h), bytes(mask))
            data = img.tobytes()
        # unicode, height, width, xAdvance, dY (top above baseline), dX, padding
        metrics += struct.pack(">7i", cp, h, w, advance, -oy, ox, 0)
        bitmaps += data
        count += 1
    header = struct.pack(">6i", count, 11, size, 0, ascent, descent)
    path.write_bytes(header + metrics + bitmaps)
    print(f"{path.name}: {count} glyphs, {path.stat().st_size} bytes")


# ---- time zones ----


def write_tz(out: Path, zones: dict):
    lines = [
        "/* Generated by tools/gen_assets.py from posix_tz_db (MIT). Do not edit. */",
        "",
        '#include "assets.h"',
        "",
        "const tz_entry_t tz_table[] = {",
    ]
    for name in sorted(zones):
        rule = zones[name]
        lines.append(f'    {{"{name}", "{rule}"}},')
    lines += ["};", "", f"const int tz_count = {len(zones)};", ""]
    (out / "tz_table_gen.c").write_text("\n".join(lines))
    print(f"time zones: {len(zones)}")


# ---- preview ----


def write_preview(path: Path, icons: list, fonts: list):
    cols = 12
    cell = 72
    rows = (len(icons) + cols - 1) // cols
    sample = "Zurück Menü Lautstärke ÄÖÜ äöüß ‹ › · … 0123 Ünïcödé Łódź"
    img = Image.new("L", (cols * cell, rows * cell + 60 * len(fonts) + 20), 255)
    d = ImageDraw.Draw(img)
    small = ImageFont.truetype(io.BytesIO(fonts[0][1]), 9)
    for i, (name, icon) in enumerate(icons):
        x, y = (i % cols) * cell, (i // cols) * cell
        img.paste(0, (x + 12, y + 4), Image.eval(icon, lambda v: v))
        d.text((x + cell / 2, y + 60), name[:14], font=small, fill=0, anchor="mm")
    y = rows * cell + 10
    for (label, ttf, size) in fonts:
        d.text((8, y), f"{label}: {sample}", font=ImageFont.truetype(io.BytesIO(ttf), size), fill=0)
        y += 60
    img.save(path)
    print(f"preview: {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--icons", type=Path, default=Path("assets/icons.txt"))
    args = ap.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    args.out.mkdir(parents=True, exist_ok=True)

    mdi = fetch(args.cache, "mdi")
    ttf = tar_member(mdi, "fonts/materialdesignicons-webfont.ttf")
    cps = mdi_codepoints(tar_member(mdi, "scss/_variables.scss").decode())
    icons = write_icons(args.out, read_icon_list(args.icons), cps, ttf)

    noto = fetch(args.cache, "noto")
    previews = []
    for name, member, size in FONTS:
        font_ttf = tar_member(noto, member)
        write_vlw(args.out / f"{name}.vlw", font_ttf, size)
        previews.append((name, font_ttf, size))

    write_tz(args.out, json.loads(fetch(args.cache, "tz")))
    write_preview(args.cache / "preview.png", icons, previews)


if __name__ == "__main__":
    main()
